%% ========================================================================
% MASTER ANALYTICS ENGINE & TELEMETRY LOGGER
% Architecture: Automated Data Extraction & Visualization Suite
% Purpose: Consumes simulated telemetry (.mat files or base workspace) to 
% mathematically prove controller stability. Generates key performance 
% indicators including RMSE Cross-Track Error, Tire Saturation limits, 
% Slip Angle Phase Portraits, and Actuator Chatter analysis.
% =========================================================================
clc; close all;

% =========================================================================
% 0. DUAL-MODE SELECTION & WORKSPACE PREP
% =========================================================================
plot_mode = questdlg('What would you like to plot?', ...
    'Analytics Engine', 'Current Workspace (Single)', 'Saved .mat Files (Compare)', 'Current Workspace (Single)');
if isempty(plot_mode)
    disp('Analytics canceled.'); return;
end

try
    ideal_path = evalin('base', 'path_waypoints');
    track_dist = evalin('base', 'dist_interp');
    v_target   = evalin('base', 'v_ref_array');
    has_ideal_track = true;
    total_track_length = track_dist(end);
catch
    has_ideal_track = false;
    total_track_length = 0;
    fprintf('\n[WARNING]: Ideal track variables not found in base workspace.\n');
end

% Inline function: Variable-Step Solver Synchronization
% Simulink's variable-step solvers produce arrays of slightly varying lengths 
% depending on plant stiffness. We pad with NaNs rather than truncating to 
% preserve the absolute time domain and prevent data loss.
pad_or_trim = @(arr, target_len) [reshape(arr(1:min(length(arr), target_len)), [], 1); NaN(max(0, target_len - length(arr)), 1)];

% =========================================================================
% MODE A: SINGLE RUN (CURRENT WORKSPACE - FULL 5 FIGURES)
% =========================================================================
if strcmp(plot_mode, 'Current Workspace (Single)')
    fprintf('Extracting telemetry from current workspace...\n');
    
    try
        % Data Extraction Logic: Handles both raw workspace variables and 
        % structured 'out' objects generated by the sim() command.
        if exist('out', 'var')
            if isa(out.Actual_X, 'timeseries')
                actual_x = out.Actual_X.Data; actual_y = out.Actual_Y.Data;
                actual_yaw = out.Actual_YawRate.Data; steer_cmd = out.Steering_Angle.Data; 
                if isprop(out, 'tout'), time_sim = out.tout; else, time_sim = out.Actual_X.Time; end
            else
                actual_x = out.Actual_X; actual_y = out.Actual_Y;
                actual_yaw = out.Actual_YawRate; steer_cmd = out.Steering_Angle;
                time_sim = (0:(length(actual_x)-1))' * 0.01;
            end
            
            try
                if isa(out.CrossTrackError, 'timeseries'), cte_data = out.CrossTrackError.Data; 
                else, cte_data = out.CrossTrackError; end
            catch
                cte_data = zeros(size(actual_x));
                for k = 1:length(actual_x)
                    dists = (ideal_path(:,1) - actual_x(k)).^2 + (ideal_path(:,2) - actual_y(k)).^2;
                    cte_data(k) = sqrt(min(dists));
                end
            end
            
            if isprop(out, 'Ideal_YawRate'), ideal_yaw = out.Ideal_YawRate.Data; else, ideal_yaw = []; end
            if isprop(out, 'Alpha_f'), alpha_f = out.Alpha_f.Data; else, alpha_f = []; end
            if isprop(out, 'Alpha_r'), alpha_r = out.Alpha_r.Data; else, alpha_r = []; end
            if isprop(out, 'SlipAngle'), beta = out.SlipAngle.Data; else, beta = []; end
        else
            temp_x = evalin('base', 'Actual_X');
            if isa(temp_x, 'timeseries')
                actual_x = temp_x.Data; actual_y = evalin('base', 'Actual_Y.Data');
                actual_yaw = evalin('base', 'Actual_YawRate.Data'); steer_cmd = evalin('base', 'Steering_Angle.Data');
                if evalin('base', 'exist(''tout'', ''var'')'), time_sim = evalin('base', 'tout'); else, time_sim = temp_x.Time; end
            else
                actual_x = temp_x; actual_y = evalin('base', 'Actual_Y');
                actual_yaw = evalin('base', 'Actual_YawRate'); steer_cmd = evalin('base', 'Steering_Angle');
                time_sim = (0:(length(actual_x)-1))' * 0.01;
            end
            
            if evalin('base', 'exist(''CrossTrackError'', ''var'')')
                temp_cte = evalin('base', 'CrossTrackError');
                if isa(temp_cte, 'timeseries'), cte_data = temp_cte.Data; else, cte_data = temp_cte; end
            else
                cte_data = zeros(size(actual_x));
                for k = 1:length(actual_x)
                    dists = (ideal_path(:,1) - actual_x(k)).^2 + (ideal_path(:,2) - actual_y(k)).^2;
                    cte_data(k) = sqrt(min(dists));
                end
            end
            
            if evalin('base', 'exist(''Ideal_YawRate'', ''var'')'), temp = evalin('base', 'Ideal_YawRate'); if isa(temp, 'timeseries'), ideal_yaw = temp.Data; else, ideal_yaw = temp; end; else, ideal_yaw = []; end
            if evalin('base', 'exist(''Alpha_f'', ''var'')'), temp = evalin('base', 'Alpha_f'); if isa(temp, 'timeseries'), alpha_f = temp.Data; else, alpha_f = temp; end; else, alpha_f = []; end
            if evalin('base', 'exist(''Alpha_r'', ''var'')'), temp = evalin('base', 'Alpha_r'); if isa(temp, 'timeseries'), alpha_r = temp.Data; else, alpha_r = temp; end; else, alpha_r = []; end
            if evalin('base', 'exist(''SlipAngle'', ''var'')'), temp = evalin('base', 'SlipAngle'); if isa(temp, 'timeseries'), beta = temp.Data; else, beta = temp; end; else, beta = []; end
        end
    catch ME
        error('Signal Extraction Failed: %s', ME.message);
    end
    
    % --- VARIABLE-STEP SOLVER FIX: SAFE PADDING ---
    target_len = min([length(actual_x), length(actual_y), length(time_sim)]);
    
    actual_x = pad_or_trim(actual_x, target_len);
    actual_y = pad_or_trim(actual_y, target_len);
    time_sim = pad_or_trim(time_sim, target_len);
    
    actual_yaw = pad_or_trim(actual_yaw, target_len);
    steer_cmd = pad_or_trim(steer_cmd, target_len);
    cte_data = pad_or_trim(cte_data, target_len);
    
    if ~isempty(ideal_yaw), ideal_yaw = pad_or_trim(ideal_yaw, target_len); end
    if ~isempty(alpha_f), alpha_f = pad_or_trim(alpha_f, target_len); end
    if ~isempty(alpha_r), alpha_r = pad_or_trim(alpha_r, target_len); end
    if ~isempty(beta), beta = pad_or_trim(beta, target_len); end
    % --------------------------------------------------------
    
    rmse_cte = sqrt(mean(cte_data.^2, 'omitnan')); max_cte = max(abs(cte_data));
    if ~isempty(ideal_yaw), max_yaw_err = max(abs(ideal_yaw - actual_yaw)); else, max_yaw_err = NaN; end
    
    actual_dist = zeros(target_len, 1); actual_speed = zeros(target_len, 1);
    for i = 2:target_len
        dx = actual_x(i) - actual_x(i-1); dy = actual_y(i) - actual_y(i-1); dt = time_sim(i) - time_sim(i-1); step_dist = sqrt(dx^2 + dy^2);
        actual_dist(i) = actual_dist(i-1) + step_dist;
        if dt > 0, actual_speed(i) = step_dist / dt; else, actual_speed(i) = actual_speed(i-1); end
    end
    avg_speed = actual_dist(end) / time_sim(end);
    if has_ideal_track, completion_pct = mean(abs(cte_data(~isnan(cte_data))) <= 0.7) * 100; else, completion_pct = 100; end
    
    this_color = '#D95319'; 
    
    % --- PLOTTING 5 FIGURES ---
    
    % FIG 1: Spatial Trajectory
    fig1 = figure('Name', 'Track Analysis', 'Color', 'w', 'Position', [50, 50, 600, 500]); hold on; grid on; axis equal;
    if has_ideal_track, plot(ideal_path(:,1), ideal_path(:,2), 'k-', 'LineWidth', 2, 'DisplayName', 'Ideal Racing Line'); end
    plot(actual_x, actual_y, '-', 'Color', this_color, 'LineWidth', 1.5, 'DisplayName', sprintf('Model (%.1f%%)', completion_pct));
    
    % Dynamic Multi-Obstacle Visualization (APF Verification)
    if evalin('base', 'exist(''enable_obstacle'', ''var'')') && evalin('base', 'enable_obstacle') == 1
        num_obs = evalin('base', 'num_obstacles');
        obs_x_val = evalin('base', 'obs_x'); obs_y_val = evalin('base', 'obs_y');
        plot(obs_x_val(1:num_obs), obs_y_val(1:num_obs), 'rp', 'MarkerFaceColor', 'r', 'MarkerSize', 14, 'DisplayName', 'Stalled Vehicle(s)');
    end
    
    title('Track Telemetry & Trajectory', 'FontSize', 12, 'FontWeight', 'bold'); xlabel('Global X (m)'); ylabel('Global Y (m)'); legend('Location', 'best');
    
    % FIG 2: Velocity & Cross-Track Error
    fig2 = figure('Name', 'Performance Profiles', 'Color', 'w', 'Position', [660, 50, 600, 600]);
    subplot(2,1,1); hold on; grid on;
    if has_ideal_track, plot(track_dist, v_target, 'k--', 'LineWidth', 2, 'DisplayName', 'Target V_{ref}'); end
    plot(actual_dist, actual_speed, '-', 'Color', this_color, 'LineWidth', 1.5, 'DisplayName', 'V_{actual}');
    title('Velocity Profile vs. Track Distance (Station)'); ylabel('Velocity (m/s)'); xlim([0, total_track_length]); legend('Location', 'best');
    subplot(2,1,2); hold on; grid on;
    plot(actual_dist, abs(cte_data), '-', 'Color', this_color, 'LineWidth', 1.5, 'DisplayName', 'Absolute CTE');
    title('Cross-Track Error (CTE) vs. Track Distance'); xlabel('Distance Traveled (m)'); ylabel('Absolute Error (m)'); xlim([0, total_track_length]); legend('Location', 'best');
    
    % FIG 3: Tire Saturation Boundaries
    if ~isempty(alpha_f)
        fig3 = figure('Name', 'Tire Saturation Analysis', 'Color', 'w', 'Position', [50, 600, 600, 300]); hold on; grid on;
        title('Tire Slip Angles (\alpha) vs. Time'); xlabel('Time (s)'); ylabel('Slip Angle (rad)');
        yline(0.087, 'r--', 'Limit (5^{\circ})', 'LineWidth', 1.5, 'HandleVisibility', 'off'); yline(-0.087, 'r--', 'LineWidth', 1.5, 'HandleVisibility', 'off');
        plot(time_sim, alpha_f, '-', 'Color', this_color, 'LineWidth', 1.2, 'DisplayName', '\alpha_f');
        if ~isempty(alpha_r), plot(time_sim, alpha_r, '-', 'Color', '#0072BD', 'LineWidth', 1.2, 'DisplayName', '\alpha_r'); end
        legend('Location', 'best');
    end
    
    % FIG 4: Phase Portrait (Mathematical Proof of Stability)
    % A stable vehicle will boundedly orbit the origin (limit cycle).
    % An unstable vehicle (spin-out) will spiral to infinity.
    if ~isempty(beta)
        fig4 = figure('Name', 'Phase Portrait', 'Color', 'w', 'Position', [660, 680, 600, 300]); hold on; grid on;
        title('Phase Portrait: Slip Angle (\beta) vs. Yaw Rate (r)'); xlabel('Slip Angle \beta (rad)'); ylabel('Yaw Rate r (rad/s)');
        xline(0, 'k-', 'HandleVisibility', 'off'); yline(0, 'k-', 'HandleVisibility', 'off'); 
        plot(beta, actual_yaw, '-', 'Color', this_color, 'LineWidth', 1.5, 'DisplayName', 'Trajectory');
        plot(beta(end), actual_yaw(end), 'rx', 'MarkerSize', 8, 'LineWidth', 2, 'HandleVisibility', 'off');
        legend('Location', 'best');
    end
    
    % FIG 5: Actuator Chatter
    fig5 = figure('Name', 'Robustness Analysis (Actuator Chatter)', 'Position', [100, 100, 1000, 400], 'Color', 'w'); hold on; grid on;
    plot(time_sim, steer_cmd * (180/pi), 'LineWidth', 1, 'Color', '#0072BD', 'DisplayName', 'Noisy Steering Signal'); 
    title('Controller Actuator Effort (Fighting 30ms Latency & Noise)', 'FontSize', 12, 'FontWeight', 'bold');
    xlabel('Time (s)'); ylabel('\delta Command (Degrees)'); legend('Location', 'best');
    dim = [.75 .65 .2 .2]; str = {sprintf('RMSE CTE: %.3f m', rmse_cte), sprintf('Peak CTE: %.3f m', max_cte), 'Latency: 30ms'};
    annotation('textbox', dim, 'String', str, 'FitBoxToText', 'on', 'BackgroundColor', 'white', 'EdgeColor', 'black');
    
    % CONSOLE OUTPUT
    fprintf('\n=== ACTIVE STABILITY: SINGLE RUN RESULTS ===\n');
    fprintf('Path Adherence      : %.1f %%\n', completion_pct);
    fprintf('Actual Average Speed  : %.2f m/s\n', avg_speed);
    fprintf('Network Latency       : 30 ms (Simulated)\n');
    fprintf('Degraded RMSE CTE     : %.3f meters\n', rmse_cte);
    fprintf('Max Instability (Yaw) : %.3f rad/s\n', max_yaw_err);
    fprintf('==============================================\n\n');
    
    save_name = input('Enter a name to save this run (or press Enter to skip): ', 's');
    if ~isempty(save_name)
        script_dir = fileparts(mfilename('fullpath')); project_dir = fileparts(script_dir); data_dir = fullfile(project_dir, 'data');
        if ~exist(data_dir, 'dir'), mkdir(data_dir); end
        save_path = fullfile(data_dir, [save_name, '.mat']);
        if exist('out', 'var'), save(save_path, 'out', 'rmse_cte', 'max_yaw_err', 'avg_speed', 'completion_pct');
        else, save(save_path, 'actual_x', 'actual_y', 'actual_yaw', 'steer_cmd', 'cte_data', 'rmse_cte', 'max_yaw_err', 'avg_speed', 'completion_pct'); end
        fprintf('Data successfully saved to: %s\n', save_path);
    end

% =========================================================================
% MODE B: COMPARATIVE MULTI-FILE OVERLAY (FULL 5 FIGURES)
% =========================================================================
else
    disp('Select the .mat data files to compare.');
    [filenames, path] = uigetfile('*.mat', 'Select Simulation Data', 'MultiSelect', 'on');
    if isequal(filenames, 0), disp('Canceled.'); return; end
    if ischar(filenames), filenames = {filenames}; end
    
    num_files = length(filenames);
    colors = {[0 0.447 0.741], [0.850 0.325 0.098], [0.466 0.674 0.188], [0.929 0.694 0.125], [0.494 0.184 0.556]};
    
    fig1 = figure('Name', 'Comparative Trajectory', 'Color', 'w', 'Position', [50, 50, 600, 500]); hold on; grid on; axis equal;
    if has_ideal_track, plot(ideal_path(:,1), ideal_path(:,2), 'k-', 'LineWidth', 2, 'DisplayName', 'Ideal Line'); end
    
    % Dynamic Multi-Obstacle Visualization (APF Verification)
    if evalin('base', 'exist(''enable_obstacle'', ''var'')') && evalin('base', 'enable_obstacle') == 1
        num_obs = evalin('base', 'num_obstacles');
        obs_x_val = evalin('base', 'obs_x'); obs_y_val = evalin('base', 'obs_y');
        plot(obs_x_val(1:num_obs), obs_y_val(1:num_obs), 'rp', 'MarkerFaceColor', 'r', 'MarkerSize', 14, 'DisplayName', 'Stalled Vehicle(s)');
    end
    
    title('Trajectory Overlay'); xlabel('Global X (m)'); ylabel('Global Y (m)');
    
    fig2 = figure('Name', 'Comparative Performance', 'Color', 'w', 'Position', [660, 50, 600, 600]);
    ax_vel = subplot(2,1,1); hold(ax_vel, 'on'); grid(ax_vel, 'on'); title(ax_vel, 'Velocity Profile'); ylabel(ax_vel, 'Velocity (m/s)');
    if has_ideal_track, plot(ax_vel, track_dist, v_target, 'k--', 'LineWidth', 2, 'DisplayName', 'Target'); end
    ax_cte = subplot(2,1,2); hold(ax_cte, 'on'); grid(ax_cte, 'on'); title(ax_cte, 'Absolute CTE'); xlabel(ax_cte, 'Distance (m)'); ylabel(ax_cte, 'Error (m)');
    
    fig3 = figure('Name', 'Comparative Tire Saturation', 'Color', 'w', 'Position', [50, 600, 600, 300]); hold on; grid on;
    title('Tire Slip Angles (\alpha_f) vs. Time'); xlabel('Time (s)'); ylabel('Front Slip Angle (rad)');
    yline(0.087, 'r--', 'Limit (5^{\circ})', 'LineWidth', 1.5, 'HandleVisibility', 'off'); yline(-0.087, 'r--', 'LineWidth', 1.5, 'HandleVisibility', 'off');
    
    fig4 = figure('Name', 'Comparative Phase Portrait', 'Color', 'w', 'Position', [660, 680, 600, 300]); hold on; grid on;
    title('Phase Portrait Overlay: Slip Angle vs. Yaw Rate'); xlabel('Slip Angle \beta (rad)'); ylabel('Yaw Rate r (rad/s)');
    xline(0, 'k-', 'HandleVisibility', 'off'); yline(0, 'k-', 'HandleVisibility', 'off');
    
    fig5 = figure('Name', 'Comparative Actuator Chatter', 'Position', [100, 100, 1000, 400], 'Color', 'w'); hold on; grid on;
    title('Controller Actuator Effort (Fighting 30ms Latency & Noise)', 'FontSize', 12, 'FontWeight', 'bold');
    xlabel('Time (s)'); ylabel('\delta Command (Degrees)');
    
    fprintf('\n=== ACTIVE STABILITY: COMPARATIVE ANALYTICS ===\n');
    fprintf('%-15s | %-10s | %-12s | %-10s\n', 'MODEL', 'PATH ADHERENCE', 'AVG SPEED', 'RMSE CTE');
    fprintf(repmat('-', 1, 56)); fprintf('\n');
    
    for i = 1:num_files
        temp = load(fullfile(path, filenames{i}));
        [~, name, ~] = fileparts(filenames{i});
        model_name = upper(strrep(strrep(name, 'RACE_DATA_', ''), '_', ' '));
        c_color = colors{mod(i-1, length(colors)) + 1};
        
        c_beta = []; c_r = []; c_steer = []; c_alpha_f = [];
        if isfield(temp, 'out')
            cx = temp.out.Actual_X.Data; cy = temp.out.Actual_Y.Data;
            
            if ismember('CrossTrackError', temp.out.who)
                if isa(temp.out.CrossTrackError, 'timeseries'), ccte = temp.out.CrossTrackError.Data; else, ccte = temp.out.CrossTrackError; end
            else
                ccte = zeros(size(cx));
                for k = 1:length(cx)
                    dists = (ideal_path(:,1) - cx(k)).^2 + (ideal_path(:,2) - cy(k)).^2;
                    ccte(k) = sqrt(min(dists));
                end
            end
            
            if ismember('tout', temp.out.who), ctime = temp.out.tout; else, ctime = temp.out.Actual_X.Time; end
            if ismember('SlipAngle', temp.out.who), if isa(temp.out.SlipAngle, 'timeseries'), c_beta = temp.out.SlipAngle.Data; else, c_beta = temp.out.SlipAngle; end; end
            if ismember('Actual_YawRate', temp.out.who), if isa(temp.out.Actual_YawRate, 'timeseries'), c_r = temp.out.Actual_YawRate.Data; else, c_r = temp.out.Actual_YawRate; end; end
            if ismember('Steering_Angle', temp.out.who), if isa(temp.out.Steering_Angle, 'timeseries'), c_steer = temp.out.Steering_Angle.Data; else, c_steer = temp.out.Steering_Angle; end; end
            if ismember('Alpha_f', temp.out.who), if isa(temp.out.Alpha_f, 'timeseries'), c_alpha_f = temp.out.Alpha_f.Data; else, c_alpha_f = temp.out.Alpha_f; end; end
        else
            cx = temp.actual_x; cy = temp.actual_y;
            if isfield(temp, 'cte_data'), ccte = temp.cte_data; else, ccte = zeros(size(cx)); end
            ctime = (0:(length(cx)-1))' * 0.01;
            if isfield(temp, 'actual_yaw'), c_r = temp.actual_yaw; end
            if isfield(temp, 'steer_cmd'), c_steer = temp.steer_cmd; else, c_steer = zeros(size(cx)); end
            if isfield(temp, 'alpha_f'), c_alpha_f = temp.alpha_f; end
        end
        
        target_len_b = min([length(cx), length(cy), length(ctime)]);
        
        cx = pad_or_trim(cx, target_len_b); cy = pad_or_trim(cy, target_len_b); 
        ctime = pad_or_trim(ctime, target_len_b); ccte = pad_or_trim(ccte, target_len_b);
        
        if ~isempty(c_beta), c_beta = pad_or_trim(c_beta, target_len_b); end
        if ~isempty(c_r), c_r = pad_or_trim(c_r, target_len_b); end
        if ~isempty(c_steer), c_steer = pad_or_trim(c_steer, target_len_b); end
        if ~isempty(c_alpha_f), c_alpha_f = pad_or_trim(c_alpha_f, target_len_b); end
        
        cdist = zeros(target_len_b, 1); cspeed = zeros(target_len_b, 1);
        for j = 2:target_len_b
            d = sqrt((cx(j)-cx(j-1))^2 + (cy(j)-cy(j-1))^2); dt = ctime(j) - ctime(j-1);
            cdist(j) = cdist(j-1) + d;
            if dt > 0, cspeed(j) = d / dt; else, cspeed(j) = cspeed(j-1); end
        end
        c_pct = mean(abs(ccte(~isnan(ccte))) <= 0.7) * 100;
        c_rmse = sqrt(mean(ccte.^2, 'omitnan'));
        c_avgspd = cdist(end) / ctime(end);
        
        plot(fig1.CurrentAxes, cx, cy, '-', 'Color', c_color, 'LineWidth', 1.5, 'DisplayName', model_name);
        plot(ax_vel, cdist, cspeed, '-', 'Color', c_color, 'LineWidth', 1.5, 'DisplayName', model_name);
        plot(ax_cte, cdist, abs(ccte), '-', 'Color', c_color, 'LineWidth', 1.5, 'DisplayName', model_name);
        
        if ~isempty(c_alpha_f), plot(fig3.CurrentAxes, ctime, c_alpha_f, '-', 'Color', c_color, 'LineWidth', 1.5, 'DisplayName', model_name); end
        if ~isempty(c_beta) && ~isempty(c_r), plot(fig4.CurrentAxes, c_beta, c_r, '-', 'Color', c_color, 'LineWidth', 1.5, 'DisplayName', model_name); end
        if ~isempty(c_steer), plot(fig5.CurrentAxes, ctime, c_steer * (180/pi), '-', 'Color', c_color, 'LineWidth', 1.0, 'DisplayName', model_name); end
        
        fprintf('%-15s | %-9.1f%% | %-8.2f m/s | %.3f m\n', model_name, c_pct, c_avgspd, c_rmse);
    end
    
    legend(fig1.CurrentAxes, 'Location', 'best'); legend(ax_vel, 'Location', 'best'); legend(ax_cte, 'Location', 'best');
    if ~isempty(fig3.CurrentAxes.Children), legend(fig3.CurrentAxes, 'Location', 'best'); end
    if ~isempty(fig4.CurrentAxes.Children), legend(fig4.CurrentAxes, 'Location', 'best'); end
    if ~isempty(fig5.CurrentAxes.Children), legend(fig5.CurrentAxes, 'Location', 'best'); end
    fprintf(repmat('=', 1, 56)); fprintf('\n\n');
end
